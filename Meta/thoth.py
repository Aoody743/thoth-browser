"""Build Thoth with dependencies outside paths containing spaces."""
import argparse
import os
import platform
import shutil
import subprocess
import sys

from pathlib import Path

SOURCE = Path(__file__).resolve().parent.parent
DEFAULT_MACOS_DEPLOYMENT_TARGET = "14.4"
sys.path.insert(0, str(SOURCE / "Meta"))
from Utils.build_vcpkg import build_vcpkg  # noqa: E402
from Utils.find_compiler import pick_host_compiler  # noqa: E402
from Utils.host_platform import Platform  # noqa: E402


def main():
    parser = argparse.ArgumentParser(description="Thoth Browser alpha2.0 macOS developer build")
    parser.add_argument("command", choices=["build", "run", "test"])
    parser.add_argument("--jobs", "-j", type=int, default=6)
    parser.add_argument("--no-build", action="store_true")
    parser.add_argument("--target", default="ladybird")
    parser.add_argument("--sdk", type=Path, help="macOS SDK root (defaults to the installed Xcode SDK)")
    parser.add_argument("--qt-prefix", type=Path, help="Qt installation prefix (defaults to Homebrew qtbase)")
    parser.add_argument("--build-root", type=Path, default=Path.home() / ".cache/thoth-browser")
    args, extra = parser.parse_known_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    if extra and args.command == "build":
        parser.error("Unexpected extra arguments")
    if extra and extra[0] == "--":
        extra = extra[1:]
    root = args.build_root.expanduser().resolve()
    if " " in str(root):
        parser.error("--build-root must not contain spaces (OpenSSL build requirement)")
    if sys.platform != "darwin":
        parser.error("This alpha build entry point currently supports macOS only")
    triplet = ("arm64" if platform.machine() == "arm64" else "x64") + "-osx-dynamic"
    build = root / "Build/release"
    vcpkg = root / "Build/vcpkg-release"
    env = os.environ.copy()
    env.update({
        "LADYBIRD_SOURCE_DIR": str(SOURCE),
        "LADYBIRD_MAIN_SOURCE_DIR": str(root),
        "VCPKG_ROOT": str(vcpkg),
        "VCPKG_MAX_CONCURRENCY": str(args.jobs),
        "VCPKG_BINARY_SOURCES": f"clear;files,{root}/Build/caches/vcpkg-binary-cache,readwrite",
        "X_VCPKG_ASSET_SOURCES": os.environ.get(
            "X_VCPKG_ASSET_SOURCES",
            "clear;x-azurl,https://vcpkg-cache.app.ladybird.org/ladybird/source-assets/,,read",
        ),
    })

    def run(command):
        subprocess.run([str(x) for x in command], cwd=SOURCE, env=env, check=True)

    if not args.no_build:
        cc, cxx = pick_host_compiler(Platform(), "cc", "c++")
        qt_prefix = args.qt_prefix
        if qt_prefix is None:
            brew = shutil.which("brew")
            if brew:
                try:
                    qt_prefix = Path(subprocess.check_output(
                        [brew, "--prefix", "qtbase"], text=True, stderr=subprocess.DEVNULL
                    ).strip())
                except subprocess.CalledProcessError:
                    pass
        if qt_prefix is None:
            qt_candidates = [Path("/opt/homebrew/opt/qtbase"), Path("/usr/local/opt/qtbase")]
            qt_prefix = next((candidate for candidate in qt_candidates
                              if (candidate / "lib/cmake/Qt6/Qt6Config.cmake").is_file()), None)
        if qt_prefix is None:
            parser.error("Qt was not found; install Homebrew qtbase or pass --qt-prefix")
        qt_prefix = qt_prefix.expanduser().resolve()
        sdk = args.sdk
        if sdk is None:
            xcode_sdk = Path(
                "/Applications/Xcode.app/Contents/Developer/Platforms/MacOSX.platform/Developer/SDKs/MacOSX.sdk"
            )
            sdk = xcode_sdk if xcode_sdk.exists() else Path(subprocess.check_output(
                ["xcrun", "--show-sdk-path"], text=True
            ).strip())
        sdk = sdk.expanduser().resolve()
        vm_header = sdk / "usr/include/mach/vm_statistics.h"
        if not vm_header.exists() or "VM_MEMORY_APPLICATION_SPECIFIC_2" not in vm_header.read_text():
            parser.error("The macOS SDK is too old for this Ladybird revision; use --sdk with a newer SDK")
        build.mkdir(parents=True, exist_ok=True)
        # Match the file generated by upstream CMake before the dependency preflight.
        (build / "build-vcpkg-variables.cmake").write_text(
            f"set(ENV{{CC}} {cc})\nset(ENV{{CXX}} {cxx})\n"
            f"set(VCPKG_OSX_DEPLOYMENT_TARGET {DEFAULT_MACOS_DEPLOYMENT_TARGET})\n"
        )
        build_vcpkg(vcpkg)
        run([vcpkg / "vcpkg", "install", f"--triplet={triplet}",
             f"--host-triplet={triplet}", f"--x-install-root={build}/vcpkg_installed",
             f"--overlay-triplets={SOURCE}/Meta/CMake/vcpkg/release-triplets", "--no-print-usage"])
        run(["cmake", "--preset", "Release", "-S", SOURCE, "-B", build,
             f"-DCMAKE_C_COMPILER={cc}", f"-DCMAKE_CXX_COMPILER={cxx}", f"-DCMAKE_OSX_SYSROOT={sdk}",
             f"-DCMAKE_OSX_DEPLOYMENT_TARGET={DEFAULT_MACOS_DEPLOYMENT_TARGET}",
             f"-DCMAKE_PREFIX_PATH={qt_prefix}"])
        run(["cmake", "--build", build, "--target", args.target, "--parallel", str(args.jobs)])
    if args.command == "run":
        run([build / "bin/Thoth Browser.app/Contents/MacOS/Thoth Browser", *extra])
    elif args.command == "test":
        thoth_tests = SOURCE / "Build/thoth-tests"
        if thoth_tests.is_dir() and (thoth_tests / "CTestTestfile.cmake").is_file():
            run(["ctest", "--test-dir", thoth_tests, "--output-on-failure", *extra])
        elif extra:
            parser.error(f"Thoth test directory does not exist: {thoth_tests}")
        else:
            print(f"Skipping Thoth unit tests; configure {thoth_tests} first.", file=sys.stderr)
        smoke_test = SOURCE / "Meta/thoth_smoke_test.py"
        bundle = build / "bin/Thoth Browser.app"
        if bundle.is_dir():
            run([sys.executable, smoke_test, "--app", bundle])
    elif extra:
        parser.error("Unexpected extra arguments")


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as error:
        sys.exit(error.returncode)
